<p><a target="_blank" href="https://en.wikipedia.org/wiki/Henri_Nouwen">Henri Nouwen</a>&#039;s life story and his work with the L&#039;Arche Daybreak community gave him the platform to write <a target="_blank" href="https://amzn.to/2XF7aw2">this great little book on Christian leadership for the future</a>. This book was published back in 1989 so obviously, the future is now.</p>
<p>Nouwen&#039;s ability to capture my attention with a story of how he was going to give a talk but God gave him a partner in the process, had me wanting to skip to the end to finish that thread. Thankfully, I did not. </p>
<p>I enjoyed his three distinct points based on Jesus&#039; leadership as seen through the temptations that Satan brought to him.</p>
<p>My favourite quote came early in the book.</p>

<x-content.quote cite="Nouwen Page 30">
<p>&quot;... I am deeply convinced that the Christian leader of the future is called to be completely irrelevant and to stand in this world with nothing to offer but his or her own vulnerable self.&quot;</p>
</x-content.quote>

<p>I highly recommend this book for anyone interested in a quick read (it took me an hour) on Christian leadership, regardless of whether you lead a large team or serve a small group. I would even recommend that anyone who does not &quot;officially&quot; lead anyone to read it and learn from it as it teaches us the posture we need to take.</p>

