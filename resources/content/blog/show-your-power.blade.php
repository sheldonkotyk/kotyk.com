<x-content.quote cite="Psalm 114:3">
<p>The sea looked and fled. </p>
</x-content.quote>

<p><strong>When the Israelites came upon the Red Sea, it wasn’t something that they were going to be able to handle on their own.</strong> It was completely outside their ability to control.</p>
<p>Behind them was an army of very angry Egyptians, wanting their slaves back. If the Egyptians caught them, it was either death or torture in their future. After the 10 plagues, it wasn’t going to be a very welcoming homecoming.</p>
<p>That is, unless God did something.</p>
<p>God had already shown his power. The 10 plagues that had recently brought Egypt to its knees were pretty clear signals that God was in charge of nature, just in case Israel had forgotten that the Creator of nature itself was involved.</p>
<p>The author of Psalm 114 doesn’t mention how Moses raised his staff to part the seas. Although that act of obedience in <a target="_blank" href="https://www.biblegateway.com/passage/?search=Exodus+14&amp;version=ESV">Exodus 14</a> was important to continue reinforcing Moses’ leadership of the people, it really didn’t do anything in itself. It was all God.</p>
<p>When God calls us to do something and there is a sea in the way — whether it is opposition from others, a visa problem preventing you from ministering overseas, or a financial shortfall — God can display his power through that!</p>
<p><em>“What ails you, O sea, that you flee?</em><em>Tremble, O earth, at the presence of the Lord … who turns the rock into a pool of water…” </em>(Psalm 114:5, 7-8).</p>
<p>If the earth trembles at his presence, why do we doubt his power? Why are we staying up at night worrying that he won’t provide what we need to do what he asks us to do?</p>
