<p>Sometimes I feel like being controversial. Then other times I feel like stating the obvious. In this article, I am going to state the obvious which in turn will create controversy.</p>
<p><strong>Chicken is not meat.</strong></p>
<p>There you have it. It seems like a simple statement but from informal polling done over the last year, it seems that other than men, many don’t realize this. Therefore, I have decided to state clear and decisively, why chicken only wishes it was meat.</p>
<p><strong>1. One of these things is not like the other one.</strong></p>
<p>Cow, Buffalo, Deer, Moose, Chicken. It is clear from this exhaustive list that chickens are different from meat producing animals. Feel free to add other meat animals to the list. Pig, horse (popular meat where Cows are God and in fast food restaurants in Russia), and the cutest meat source, rabbit.</p>
<p><strong>2. Meat isn’t hatched.</strong></p>
<p>What came first the chicken or the egg? It is very clear from the creation of the world that chickens and other birds were different than other creatures. It is obvious that meat is creating during the time spent in the mother’s womb and that an egg is meant to be eaten as a side dish to bacon. This is also the reason reptiles are considered a wanna-be meat.</p>
<p><strong>3. Meat has 4 Legs.</strong></p>
<p>When it comes right down to it, the number of legs the species normally has is a major reason why chicken’s aren’t meat. Cows, pigs, buffalos and rabbits all have four legs. Chicken’s have two. Why does this make a difference? Simple, more meat.</p>
<p><strong>4. No feathers and you can hang the head on a wall.</strong></p>
<p>It is better to skin a deer than pluck a chicken, plus you can take the head to the nearest taxi guy and get him to stuff it and hang it on a wall. Ever seen a chicken head hanging on a trophy wall?</p>
<p><strong>5. All you can eat ribs.</strong></p>
<p>Have you ever seen restaurants with all you can eat ribs that give you chicken? No? The reason is that All you can eat places know that meat and chicken are not the same.</p>
<p><strong>6. Buffalo Wings.</strong></p>
<p>Even chicken wings need to be given a name like buffalo to make them worth eating.</p>
<p><strong>7. Diseases.</strong></p>
<p>E.Coli. A disease one gets from eating under-cooked meat. Ever heard of someone getting E.Coli from chicken? No, you get Salmonella from chicken which is named after a fish… another non-meat source.</p>
<p><strong>8. Mad Cow.</strong></p>
<p>Ever heard of a mad chicken? Of course not! This is due to them not being meat.</p>
<p><strong>9. Hamburger vs Chicken Burger.</strong></p>
<p>When one orders a hamburger, they get cow, not pig. That is due to meat sources being interchangeable. However, you have to specifically order a “Chicken” burger.</p>
<p><strong>10. You need to leave the skin on for taste.</strong></p>
<p>This is one of the classic examples of why chicken is not meat.</p>
<p><strong>11. Chickens walk funny.</strong></p>
<p>Birds in general are dumb and walk like they just got kicked in the rear end.</p>
<p>NOTE: I am not biased against chickens in general. Whenever I eat at Wendy’s I order the Spicy Chicken Combo and another side of 6 chicken nuggets. After all, Wendy’s has the best salads.</p>
