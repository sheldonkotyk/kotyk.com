<h2>Father, Son, Grandpa</h2>

<x-content.image-with-caption image="dad.png" locate="right" />

<p>Ostap Nestor (Nes) Kotyk of Medicine Hat, Alberta, passed away peacefully on October 3, 2023 at the age of 75 years.</p>
<p>Nes was born in Canora, Saskatchewan to Steve and Nellie Kotyk (Skoretz). He went to school in Buchanan and helped on the family farm. He worked in banking but retail was his calling. His stores carried electronics, musical instruments, books, and health food in various locations including Winnipeg MB, Estevan SK, Squamish BC, Medicine Hat and Lethbridge AB. He loved his customers and would spend hours with them, talking about current events, his faith, and anything else people wanted to discuss.</p>
<p>He enjoyed hockey, and slowpitch, and played as long as his body would allow. In the summers he could be seen with his family on the lakes water-skiing. He was involved with Youth for Christ, Hockey Ministries International, and would lead Sunday School classes.</p>
<p>Nes is survived by his children: Sheldon (Julie) and Scott, as well as his brothers Ernest (Harmony) and Danny (Peggy). Giving him incredible joy were his grandchildren: Kristin, Ava, and Jamie Kotyk, as well as Zoë DeNobrega.</p>
<p>He is predeceased by his parents Steve and Nellie Kotyk.</p>
